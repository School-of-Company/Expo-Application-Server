CREATE TABLE tb_program_session_application (
    id UUID PRIMARY KEY,
    expo_id VARCHAR(36) NOT NULL,
    program_type VARCHAR(8) NOT NULL CHECK (program_type IN ('STANDARD', 'TRAINING')),
    program_id BIGINT NOT NULL CHECK (program_id > 0),
    group_id UUID NOT NULL,
    participant_id BIGINT NOT NULL CHECK (participant_id > 0),
    trainee_id BIGINT CHECK (trainee_id > 0),
    status VARCHAR(10) NOT NULL CHECK (status IN ('CONFIRMED', 'WAITING', 'CANCELLED')),
    definition_snapshot JSONB NOT NULL CHECK (jsonb_typeof(definition_snapshot) = 'object'),
    form_id UUID NOT NULL,
    form_version BIGINT NOT NULL CHECK (form_version > 0),
    questions_snapshot JSONB NOT NULL CHECK (jsonb_typeof(questions_snapshot) = 'array'),
    answers_snapshot JSONB NOT NULL CHECK (jsonb_typeof(answers_snapshot) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (status <> 'CONFIRMED' OR program_type <> 'TRAINING' OR trainee_id IS NOT NULL)
);

CREATE UNIQUE INDEX uk_program_session_active_participant_group
    ON tb_program_session_application (expo_id, program_type, group_id, participant_id)
    WHERE status IN ('CONFIRMED', 'WAITING');
CREATE INDEX ix_program_session_program
    ON tb_program_session_application (program_type, program_id, status);

CREATE TABLE tb_program_session_receipt (
    expo_id VARCHAR(36) NOT NULL,
    participant_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    command JSONB NOT NULL,
    receipt JSONB NOT NULL,
    application_id UUID NOT NULL REFERENCES tb_program_session_application(id),
    PRIMARY KEY (expo_id, participant_id, idempotency_key)
);

CREATE TABLE tb_program_session_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id UUID NOT NULL REFERENCES tb_program_session_application(id),
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
